import type { HTMLAttributes } from "react";
import { cn } from "@/lib/utils";

export function Card({ className, ...props }: HTMLAttributes<HTMLDivElement>) {
  return (
    <div
      data-slot="card"
      className={cn(
        "rounded-xl border border-border bg-card text-foreground shadow-[0_1px_2px_rgb(0_0_0/0.25)]",
        className,
      )}
      {...props}
    />
  );
}

